import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const operator=path.resolve(process.env.CODESHIP_OPERATOR??path.join(import.meta.dirname,'../../../devkit/codeship'));
const {githubApi}=await import(pathToFileURL(path.join(operator,'.container/github.mjs')));
const {validateManifest}=await import(pathToFileURL(path.join(operator,'.container/release-policy.mjs')));
const tag=process.argv[2];if(tag!=='v-0.1.6')throw Error('Select the explicitly approved LogicX release v-0.1.6');
const repository='CODEXSUN/logicx-app';
const commit=await githubApi('/repos/'+repository+'/commits/'+tag);
const runs=await githubApi('/repos/'+repository+'/actions/runs?head_sha='+commit.sha+'&per_page=100');
if(!runs.workflow_runs.some(r=>r.path==='.github/workflows/release.yml'&&r.head_branch===tag&&r.status==='completed'&&r.conclusion==='success'))throw Error('Tagged workflow has not succeeded');
const release=await githubApi('/repos/'+repository+'/releases/tags/'+tag);
if(release.draft||release.prerelease)throw Error('Stable release required');
const asset=release.assets.find(x=>x.name==='release-manifest.json');if(!asset)throw Error('Missing manifest');
const manifest=validateManifest(JSON.parse((await githubApi('/repos/'+repository+'/releases/assets/'+asset.id,{raw:true})).toString()),{owner:'apps/logicx-app',repository,tag,commit:commit.sha});
const contract=JSON.parse(await readFile(new URL('./release.json',import.meta.url)));
if(manifest.frappeImage!==contract.frappeImage||manifest.redisImage!==contract.redisImage||JSON.stringify(manifest.target)!==JSON.stringify(contract.target)||!Object.keys(manifest.frappeMigrations??{}).length)throw Error('Bench release contract mismatch');
const directory=path.resolve(import.meta.dirname,'../.codeship/releases');await mkdir(directory,{recursive:true});
const file=path.join(directory,'logicx-v-0.1.6.json');
await writeFile(file,JSON.stringify({schema:1,source:'github',approvedAt:new Date().toISOString(),services:{'logicx-app':manifest}},null,2),{mode:0o600,flag:'wx'});
console.log(file);
